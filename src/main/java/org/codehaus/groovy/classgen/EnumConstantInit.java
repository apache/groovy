import static org.objectweb.asm.Opcodes.ACC_SYNTHETIC;
import static org.objectweb.asm.Opcodes.DUP;
import static org.objectweb.asm.Opcodes.INVOKESPECIAL;
import static org.objectweb.asm.Opcodes.NEW;

/**
 * Initializes an enum constant by calling a constructor of the enum directly.
 * <p>
 * The {@code $INIT} helper generated by {@link EnumVisitor} spreads an {@code Object[]}
 * over the constructors of the enum, which means the meta class selects the constructor
 * at run time by reflecting over {@code getDeclaredConstructors()}.  Where that reflection
 * is unavailable — a GraalVM native image for which the enum was not registered, or an
 * Android application whose code shrinker stripped the reflective-only constructor —
 * the static initializer of the enum fails.  When both the constructor the meta class
 * selects and the arguments it receives are known at compile time, the constructor can
 * be called there instead.  That is the case for
 * <ul>
 * <li>a constant that supplies no arguments of its own, when the enum has a
 * {@code (String,int)} constructor: the arguments are exactly the name and the ordinal;
 * and for</li>
 * <li>a constant whose arguments are all literals (constants such as {@code 'a'},
 * {@code 1} or {@code true}, {@code null}, and class literals), when exactly one
 * constructor that is neither synthetic nor varargs has that many parameters, each of
 * them is of the type of its literal, of the primitive type of a wrapper literal, or of a
 * type other than {@code Boolean} that the literal extends or implements ({@code null}
 * goes to any parameter that is not primitive), and no varargs constructor has that many
 * parameters if the last argument is {@code null}.  The meta class then selects that
 * constructor: it does not list synthetic constructors, and the penalty it adds to the
 * distance of a varargs constructor outweighs the distance of the constructor of matching
 * arity, unless the varargs constructor has that arity and the last argument is
 * {@code null}, which is weighed as the array.  The cast that {@code $INIT} applies to
 * each argument before the call returns the argument itself, or for a primitive parameter
 * the value of the wrapper, so the direct call receives exactly what {@code $INIT} would
 * pass.  A {@code Boolean} parameter takes no literal but {@code null}, as the cast to
 * {@code Boolean} calls {@code asBoolean} on any other value, which a category or a meta
 * class may change.</li>
 * </ul>
 * Anything else, such as a GString for a String parameter, an argument the meta class
 * would convert (an {@code int} literal for a {@code long} parameter), overloaded
 * constructors of the same arity or an argument that is not a literal, keeps the
 * {@code $INIT} call.  The constants of an enum are created alike, so one constant that
 * does not qualify keeps every constant of the enum on the {@code $INIT} path.
 * <p>
 * The static initializer of the enum keeps its {@code $INIT} calls until the class
 * generator starts on the enum, so transforms, the type checker and the static compiler
 * see them, and may rewrite them, as before.  Only then are they replaced (see
 * {@link #substitute(ClassNode)}), judged as all of these left them: the arguments of a
 * call are the ones passed to the constructor, and they are loaded by the class generator
 * just as they would be for that call.  A constant whose call is no longer a call of
 * {@code $INIT} with its name and ordinal keeps every constant of the enum on the calls
 * as they are.
 * <p>
 * One consequence of the direct call is deliberate.  Where the {@code $INIT} call
 * dispatches through the meta class of the enum — which selects the constructor — the
 * direct call does not, so a meta class registered before the enum initializes no longer
 * sees the constants being created.  That holds for an enum whose constants all have
 * literal arguments as much as for one whose constants have none.  Declaring a constant
 * with an explicit empty argument list, e.g. {@code ONE()}, supplies the same name and
 * ordinal through the {@code $INIT} path and so restores this behaviour for that enum.
 * Where every constant has arguments, that form is not available: one argument that is
 * not a literal, such as {@code 'one'.toString()} in place of {@code 'one'}, restores it
 * for the whole enum.
 */
final class EnumConstantInit extends BytecodeExpression {

    private static final Parameter[] NAME_AND_ORDINAL = params(param(ClassHelper.STRING_TYPE, "name"), param(int_TYPE, "ordinal"));

    /**
     * The node metadata key of the statements that assign the constants of an enum.
     */
    private static final Object CONSTANT_ASSIGNMENTS = new Object();

    private final ClassNode enumClass;
    private final String name;
    private final int ordinal;
    private final ConstructorNode constructor;
    private final List<Expression> arguments;
    private final Expression initCall;

    private EnumConstantInit(final ClassNode enumClass, final String name, final int ordinal,
                             final ConstructorNode constructor, final List<Expression> arguments, final Expression initCall) {
        super(enumClass.getPlainNodeReference());
        this.enumClass = enumClass;
        this.name = name;
        this.ordinal = ordinal;
        this.constructor = constructor;
        this.arguments = arguments;
        this.initCall = initCall;
        setSourcePosition(initCall);
    }

    /**
     * Records the statements of the static initializer of the given enum that assign its
     * constants, in the order of their ordinals, for {@link #substitute(ClassNode)}.
     */
    static void record(final ClassNode enumClass, final List<ExpressionStatement> assignments) {
        enumClass.putNodeMetaData(CONSTANT_ASSIGNMENTS, assignments);
    }

    /**
     * Replaces the {@code $INIT} call of each constant of the given enum with a direct
     * constructor call if every constant qualifies, and otherwise leaves the static
     * initializer as it is.  The class generator calls this before it writes the enum, so
     * the calls are judged as the transforms, the type checker and the static compiler left
     * them.  Only an enum whose constants were recorded by {@link EnumVisitor} is considered.
     * <p>
     * A transform that rewrites the {@code $INIT} calls therefore decides which way the
     * constants are created, and so whether the enum needs constructor reflection: adding a
     * literal argument to the call of every constant can move the enum onto the direct
     * calls, while replacing one call, or adding an argument that is not a literal, keeps
     * it on the calls as the transforms left them.  Anything that reads the static
     * initializer before the class generator starts sees the {@code $INIT} calls.
     */
    static void substitute(final ClassNode enumClass) {
        List<ExpressionStatement> assignments = enumClass.getNodeMetaData(CONSTANT_ASSIGNMENTS);
        if (assignments == null) return;
        enumClass.removeNodeMetaData(CONSTANT_ASSIGNMENTS);

        int n = assignments.size();
        List<EnumConstantInit> inits = new ArrayList<>(n);
        for (int ordinal = 0; ordinal < n; ordinal += 1) {
            EnumConstantInit init = directInit(enumClass, ordinal, assignments.get(ordinal).getExpression());
            if (init == null) return; // the constants of an enum are created alike
            inits.add(init);
        }
        for (int ordinal = 0; ordinal < n; ordinal += 1) {
            ((BinaryExpression) assignments.get(ordinal).getExpression()).setRightExpression(inits.get(ordinal));
        }
    }

    /**
     * Returns the direct constructor call for the constant with the given ordinal, or
     * {@code null} if its assignment is no longer {@code CONSTANT = $INIT(name, ordinal, ...)}
     * or the meta class could select another constructor or convert an argument.
     */
    private static EnumConstantInit directInit(final ClassNode enumClass, final int ordinal, final Expression expression) {
        if (!(expression instanceof BinaryExpression assignment) || assignment.getOperation().getType() != Types.ASSIGN
                || !(assignment.getLeftExpression() instanceof FieldExpression field)) return null;
        Expression initCall = assignment.getRightExpression();
        TupleExpression tuple = initArguments(enumClass, initCall);
        if (tuple == null) return null;
        String name = field.getFieldName();
        List<Expression> expressions = tuple.getExpressions();
        if (expressions.size() < 2 || !isConstant(expressions.get(0), name) || !isConstant(expressions.get(1), ordinal)) return null;
        List<Expression> arguments = expressions.subList(2, expressions.size());
        ConstructorNode constructor = selectConstructor(enumClass, arguments);
        if (constructor == null) return null;
        return new EnumConstantInit(enumClass, name, ordinal, constructor, arguments, initCall);
    }

    /**
     * Returns the arguments of the given expression if it calls the {@code $INIT} helper of
     * the given enum, in the form {@link EnumVisitor} gives it or in the form the static
     * compilation transformer turns it into, or {@code null} otherwise.
     */
    private static TupleExpression initArguments(final ClassNode enumClass, final Expression expression) {
        Expression arguments;
        if (expression instanceof StaticMethodCallExpression call
                && "$INIT".equals(call.getMethod()) && enumClass.equals(call.getOwnerType())) {
            arguments = call.getArguments();
        } else if (expression instanceof MethodCallExpression call
                && "$INIT".equals(call.getMethodAsString()) && !call.isSpreadSafe()
                && call.getObjectExpression() instanceof ClassExpression owner && enumClass.equals(owner.getType())) {
            arguments = call.getArguments();
        } else {
            return null;
        }
        return arguments instanceof TupleExpression tuple ? tuple : null;
    }

    /**
     * Returns the constructor the meta class is certain to select for a constant with the
     * given arguments, which follow its name and ordinal, and to which it passes them on
     * unchanged, or {@code null} if that cannot be shown.
     */
    private static ConstructorNode selectConstructor(final ClassNode enumClass, final List<Expression> arguments) {
        if (arguments.isEmpty()) return enumClass.getDeclaredConstructor(NAME_AND_ORDINAL);

        int nArguments = arguments.size() + 2; // the name and the ordinal come first
        boolean lastIsNull = isNull(arguments.get(arguments.size() - 1));
        ConstructorNode match = null;
        for (ConstructorNode ctor : enumClass.getDeclaredConstructors()) {
            Parameter[] parameters = ctor.getParameters();
            int nParameters = parameters.length;
            if (nParameters > 0 && parameters[nParameters - 1].getType().isArray()) {
                // the meta class may call a varargs constructor with the arguments, but adds a
                // penalty to its distance that outweighs the distance of the constructor of
                // matching arity, unless it has the arity of the call and the last argument
                // is null, which is weighed as the array
                if (nParameters == nArguments && lastIsNull) return null;
                continue;
            }
            if (nParameters == nArguments) {
                if (match != null) return null; // more than one candidate
                match = ctor;
            }
        }
        if (match == null || (match.getModifiers() & ACC_SYNTHETIC) != 0) return null; // the meta class skips synthetic constructors

        Parameter[] parameters = match.getParameters();
        if (!ClassHelper.isStringType(parameters[0].getType()) || !ClassHelper.isPrimitiveInt(parameters[1].getType())) return null;
        for (int i = 0, n = arguments.size(); i < n; i += 1) {
            if (!isPassedUnchanged(arguments.get(i), parameters[i + 2].getType())) return null;
        }
        return match;
    }

    private static boolean isNull(final Expression expression) {
        return expression instanceof ConstantExpression constant && constant.isNullExpression();
    }

    private static boolean isConstant(final Expression expression, final Object value) {
        return expression instanceof ConstantExpression constant && value.equals(constant.getValue());
    }

    /**
     * Tells whether the argument is a literal that the meta class accepts for a parameter
     * of the given type and that the cast before the call leaves as it is.  The cast to
     * {@code Boolean} with invokedynamic returns {@code null} as it is, but calls
     * {@code asBoolean} through the meta class on any other value, so {@code null} is the
     * only literal it is certain to leave alone; a {@code boolean} parameter unboxes a
     * {@code Boolean} without calling it.
     */
    private static boolean isPassedUnchanged(final Expression argument, final ClassNode parameterType) {
        ClassNode type = parameterType.redirect();
        ClassNode valueType;
        if (argument instanceof ClassExpression) {
            valueType = ClassHelper.CLASS_Type;
        } else if (argument instanceof ConstantExpression constant) {
            if (constant.getValue() == null) return !ClassHelper.isPrimitiveType(type);
            valueType = ClassHelper.getWrapper(constant.getType()); // a primitive constant is passed boxed
        } else {
            return false;
        }
        if (ClassHelper.isPrimitiveType(type)) {
            return ClassHelper.getWrapper(type).equals(valueType);
        }
        return !ClassHelper.isWrapperBoolean(type) && ClassNodeUtils.isCompatibleWith(valueType, type);
    }

    @Override
    public String getText() {
        return initCall.getText();
    }

    /**
     * Writes the constructor call when the visitor is the class generator, which loads the
     * arguments; any other visitor visits the {@code $INIT} call that this expression replaces.
     */
    @Override
    public void visit(final GroovyCodeVisitor visitor) {
        if (visitor instanceof AsmClassGenerator generator) {
            WriterController controller = generator.getController();
            write(controller.getMethodVisitor(), generator);
            controller.getOperandStack().push(getType());
        } else {
            initCall.visit(visitor);
        }
    }

    /**
     * Writes the constructor call of a constant without arguments of its own.  The arguments
     * of any other constant can only be loaded by the class generator, through
     * {@link #visit(GroovyCodeVisitor)}.
     */
    @Override
    public void visit(final MethodVisitor mv) {
        if (!arguments.isEmpty()) {
            throw new GroovyBugError("The arguments of enum constant " + name + " are loaded by the class generator");
        }
        write(mv, null);
    }

    private void write(final MethodVisitor mv, final AsmClassGenerator generator) {
        Parameter[] parameters = constructor.getParameters();
        String owner = BytecodeHelper.getClassInternalName(enumClass);
        mv.visitTypeInsn(NEW, owner);
        mv.visitInsn(DUP);
        mv.visitLdcInsn(name);
        BytecodeHelper.pushConstant(mv, ordinal);
        if (!arguments.isEmpty()) {
            OperandStack operandStack = generator.getController().getOperandStack();
            for (int i = 0, n = arguments.size(); i < n; i += 1) {
                arguments.get(i).visit(generator);
                ClassNode type = parameters[i + 2].getType();
                if (ClassHelper.isPrimitiveType(type)) {
                    operandStack.doGroovyCast(type); // unbox a wrapper literal
                } else {
                    operandStack.box();
                }
            }
            operandStack.remove(arguments.size());
        }
        mv.visitMethodInsn(INVOKESPECIAL, owner, "<init>", BytecodeHelper.getMethodDescriptor(ClassHelper.VOID_TYPE, parameters), false);
    }
}
