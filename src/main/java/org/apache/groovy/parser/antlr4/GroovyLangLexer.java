package org.apache.groovy.parser.antlr4;

import org.antlr.v4.runtime.CharStream;
import org.antlr.v4.runtime.CharStreams;
import org.antlr.v4.runtime.Lexer;
import org.antlr.v4.runtime.LexerNoViableAltException;
import org.antlr.v4.runtime.Token;
import org.antlr.v4.runtime.atn.ATN;
import org.antlr.v4.runtime.atn.LexerATNSimulator;
import org.apache.groovy.parser.antlr4.internal.atnmanager.LexerAtnManager;

import java.io.IOException;
import java.io.Reader;

/**
 * The lexer for Groovy programming language, which is based on the lexer generated by Antlr4
 */
public class GroovyLangLexer extends GroovyLexer {
    public GroovyLangLexer(Reader reader) throws IOException {
        this(CharStreams.fromReader(reader));
    }

    public GroovyLangLexer(CharStream input) {
        super(input);

        this.setInterpreter(new PositionAdjustingLexerATNSimulator(this, LexerAtnManager.INSTANCE.getATN()));
    }

    /**
     * Returns the next token, with a special case for EOF after a bare {@code $} in a GString.
     * <p>
     * After {@code GStringBegin} or {@code GStringPart} matches a trailing {@code $} at the
     * end of input, Antlr marks {@code _hitEOF} and would skip
     * {@link #GSTRING_TYPE_SELECTOR_MODE} entirely on the subsequent call.  Detect that
     * situation and report the dollar-body error instead of a generic unexpected-EOF parse
     * failure.
     *
     * @return the next token from the input
     */
    @Override
    public Token nextToken() {
        if (_hitEOF && isGStringDollarSelectorMode()) {
            throw new GroovySyntaxError(
                    illegalGStringDollarMessage(Token.EOF),
                    GroovySyntaxError.LEXER,
                    getLine(),
                    getCharPositionInLine() + 1);
        }
        return super.nextToken();
    }

    /**
     * Report a lexical error.  When the failure is inside
     * {@link #GSTRING_TYPE_SELECTOR_MODE} (after a {@code $} in a GString), emit the
     * dedicated dollar-body diagnostic instead of Antlr's generic token-recognition message.
     *
     * @param e the recognition failure raised by the ATN simulator
     */
    @Override
    public void notifyListeners(final LexerNoViableAltException e) {
        if (isGStringDollarSelectorMode()) {
            getErrorListenerDispatch().syntaxError(
                    this, null, _tokenStartLine, _tokenStartCharPositionInLine,
                    illegalGStringDollarMessage(), e);
            return;
        }
        super.notifyListeners(e);
    }

    /**
     * Abort lexing on the first lexical error.  For an invalid character after {@code $}
     * in a GString, throw {@link GroovySyntaxError} so the parser layer can surface a
     * source-located syntax error without retrying SLL→LL or falling back to a generic
     * exception message.
     *
     * @param e the recognition failure raised by the ATN simulator
     */
    @Override
    public void recover(final LexerNoViableAltException e) {
        if (isGStringDollarSelectorMode()) {
            // Column is 1-based; _tokenStartCharPositionInLine is 0-based (Antlr convention).
            throw new GroovySyntaxError(
                    illegalGStringDollarMessage(),
                    GroovySyntaxError.LEXER,
                    _tokenStartLine,
                    _tokenStartCharPositionInLine + 1);
        }
        // if some lexical error occurred, stop parsing!
        throw e;
    }

    @Override
    protected void rollbackOneChar() {
        ((PositionAdjustingLexerATNSimulator) getInterpreter()).resetAcceptPosition(getInputStream(), _tokenStartCharIndex - 1, _tokenStartLine, _tokenStartCharPositionInLine - 1);
    }

    /**
     * Whether the lexer is choosing between {@code ${...}} and {@code $identifier} after a
     * dollar in a GString (double-quoted, triple-double-quoted, slashy or dollar-slashy).
     */
    private boolean isGStringDollarSelectorMode() {
        return GSTRING_TYPE_SELECTOR_MODE == _mode;
    }

    /**
     * Build the user-facing message for an illegal character (or EOF) immediately after
     * {@code $} in a GString.  When a concrete character is available it is appended so the
     * diagnostic names both the rule and the offending input.
     */
    private String illegalGStringDollarMessage() {
        return illegalGStringDollarMessage(_input.LA(1));
    }

    /**
     * @param c the code point at the failure site, or {@link Token#EOF}
     */
    private String illegalGStringDollarMessage(final int c) {
        // Antlr leaves the input index at the unrecognised character for LexerNoViableAltException.
        if (Token.EOF == c) {
            return "Illegal string body character after dollar sign";
        }
        return "Illegal string body character after dollar sign: " + getCharErrorDisplay(c);
    }

    /**
     * Line and column tracking for the Groovy lexer.
     * <p>
     * The ATN simulator's per-character {@code consume} is package-private and
     * final, and the DFA loop calls it directly, so a {@code consume(CharStream)}
     * override never sees normal tokens. That method advances the line only on
     * {@code \n}. A bare {@code \r} is also a line ending ({@code \r\n} is one),
     * which is what {@code LineTerminator} lexes and what {@code BufferedReader}
     * reports to the editor. After each token, if this file contains a bare CR,
     * the end position is recomputed from the token text. Files with no bare CR
     * pay for one scan and then take the unchanged simulator path.
     * <p>
     * One lexer owns this simulator and is not matched from two threads.
     */
    private static class PositionAdjustingLexerATNSimulator extends LexerATNSimulator {
        /** Stream already scanned for a bare CR, or {@code null} if not yet. */
        private CharStream scannedInput;
        /** {@code true} when {@link #scannedInput} contains a CR not followed by LF. */
        private boolean bareCr;

        public PositionAdjustingLexerATNSimulator(Lexer recog, ATN atn) {
            super(recog, atn);
        }

        protected void resetAcceptPosition(CharStream input, int index, int line, int charPositionInLine) {
            input.seek(index);
            this.line = line;
            this.charPositionInLine = charPositionInLine;
            this.consume(input);
        }

        /**
         * {@inheritDoc}
         * <p>
         * Used by rollback and by predicate speculation. The DFA loop does not
         * call this overload. A bare CR ends the line; a CR before LF does not,
         * because the following LF does.
         */
        @Override
        public void consume(CharStream input) {
            int cur = input.LA(1);
            if (cur == '\r' && input.LA(2) != '\n') {
                line++;
                charPositionInLine = 0;
                input.consume();
                return;
            }
            super.consume(input);
        }

        @Override
        public int match(CharStream input, int mode) {
            if (!fileHasBareCr(input)) {
                return super.match(input, mode);
            }
            int startLine = line;
            int startColumn = charPositionInLine;
            int startIndex = input.index();
            int type = super.match(input, mode);
            correctBareCr(input, startIndex, startLine, startColumn);
            return type;
        }

        /**
         * One forward scan per stream. The result is reused for every later
         * token of that same stream. {@link CharStream#consume()} moves the
         * index only; it does not touch {@link #line}.
         */
        private boolean fileHasBareCr(CharStream input) {
            if (input == scannedInput) {
                return bareCr;
            }
            int index = input.index();
            boolean found = false;
            try {
                input.seek(0);
                while (true) {
                    int c = input.LA(1);
                    if (c == Token.EOF) {
                        break;
                    }
                    if (c == '\r' && input.LA(2) != '\n') {
                        found = true;
                        break;
                    }
                    input.consume();
                }
            } finally {
                input.seek(index);
            }
            scannedInput = input;
            bareCr = found;
            return found;
        }

        /**
         * Recompute the simulator position for a token that contains a bare CR.
         * A CR at the end of the token whose next character is LF is the first
         * half of a CRLF owned by the following token (GString {@code more}
         * fragments match one character at a time) and must not add a line.
         * The position is applied only when a bare CR was actually present, so
         * a token made entirely of LF or CRLF keeps the simulator's own count.
         */
        private void correctBareCr(CharStream input, int startIndex, int startLine, int startColumn) {
            int end = input.index();
            if (end <= startIndex) {
                return;
            }
            int correctedLine = startLine;
            int correctedColumn = startColumn;
            boolean bare = false;
            try {
                for (int i = startIndex; i < end; ) {
                    input.seek(i);
                    int c = input.LA(1);
                    if (c == '\n') {
                        correctedLine++;
                        correctedColumn = 0;
                        i++;
                    } else if (c == '\r') {
                        if (i + 1 < end) {
                            input.seek(i + 1);
                            if (input.LA(1) == '\n') {
                                correctedLine++;
                                correctedColumn = 0;
                                i += 2;
                                continue;
                            }
                        } else {
                            input.seek(end);
                            if (input.LA(1) == '\n') {
                                correctedColumn++;
                                i++;
                                continue;
                            }
                        }
                        bare = true;
                        correctedLine++;
                        correctedColumn = 0;
                        i++;
                    } else {
                        correctedColumn++;
                        i++;
                    }
                }
            } finally {
                input.seek(end);
            }
            if (bare) {
                line = correctedLine;
                charPositionInLine = correctedColumn;
            }
        }
    }
}
