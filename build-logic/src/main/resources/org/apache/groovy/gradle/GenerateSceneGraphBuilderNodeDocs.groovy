/**
 * Generates the AsciiDoc node reference for SceneGraphBuilder.
 *
 * This script introspects a live SceneGraphBuilder instance to discover all
 * registered nodes, their registration groups and the JavaFX classes they
 * create. It produces a single file (_groovy-fx-nodes.adoc) containing one
 * summary table per group, with each JavaFX class linked to its OpenJFX
 * javadoc page, followed by the builder's explicit methods.
 *
 * Usage:
 *   groovy GenerateSceneGraphBuilderNodeDocs.groovy [outputDir]
 *
 * If outputDir is omitted, output goes to src/spec/doc under this subproject.
 * JavaFX must be on the classpath; no toolkit is started.
 */

import org.apache.groovy.groovyfx.SceneGraphBuilder
import org.apache.groovy.groovyfx.factory.NodeFactory
import org.apache.groovy.groovyfx.factory.PassThruFactory

def outputDir = args.length > 0 ? new File(args[0]) : new File('src/spec/doc')
outputDir.mkdirs()

def builder = new SceneGraphBuilder()

// Collect registration groups (categories) - these come from the register*() method names
Map<String, Set<String>> groups = [:]
builder.registrationGroups.each { groupName ->
    def items = builder.getRegistrationGroupItems(groupName)
    if (items && groupName) {
        groups[groupName] = items
    }
}

// Human-friendly category names derived from method name suffixes, e.g. "SupportNodes" -> "Support Nodes"
def categoryLabel = { String groupName ->
    groupName.replaceAll(/([a-z])([A-Z])/, '$1 $2')
             .replaceAll(/([A-Z]+)([A-Z][a-z])/, '$1 $2')
}

/**
 * JavaFX classes for the factories that do not create a bean of a fixed class.
 */
def knownClasses = [
    'series': javafx.scene.chart.XYChart.Series,
]

/**
 * Determine the JavaFX class a node creates, or null for nodes that only
 * arrange their children (the BorderPane positions, bind).
 */
def resolveClass = { String nodeName, groovy.util.Factory factory ->
    if (knownClasses.containsKey(nodeName)) return knownClasses[nodeName]
    if (factory instanceof NodeFactory) return factory.beanClass
    if (factory instanceof PassThruFactory) return factory.restrictedType
    null
}

/**
 * The OpenJFX module that publishes a class, taken from the name of the jar it
 * was loaded from (javafx-controls-21.0.8-linux.jar -> javafx.controls).
 */
static String javafxModule(Class clazz) {
    def location = clazz.protectionDomain?.codeSource?.location?.path
    def m = location ? (new File(location).name =~ /^(javafx-[a-z]+)-/) : null
    m?.find() ? m.group(1).replace('-', '.') : null
}

/**
 * Render a class as a monospaced link to its OpenJFX javadoc page, or plain
 * when it is not a JavaFX class or its module is unknown.
 */
static String classLink(Class clazz) {
    // javadoc addresses a nested class by its dotted name, e.g. XYChart.Series
    String display = clazz.name.substring(clazz.package.name.length() + 1).replace('$', '.')
    String module = clazz.name.startsWith('javafx.') ? javafxModule(clazz) : null
    if (module == null) return "`${display}`"
    String path = clazz.package.name.replace('.', '/') + '/' + display + '.html'
    "`link:https://openjfx.io/javadoc/21/${module}/${path}[${display}]`"
}

def outFile = new File(outputDir, '_groovy-fx-nodes.adoc')
def out = new StringBuilder()
out << "// Generated by GenerateSceneGraphBuilderNodeDocs.groovy - do not edit manually\n"
out << "[[groovy-fx-nodes]]\n"
out << "= SceneGraphBuilder Node Reference\n\n"
out << "The following tables list all nodes available in `SceneGraphBuilder`, grouped by\n"
out << "category, with the JavaFX class each one creates. A leaf node takes no nested nodes.\n\n"

// Explicit methods (fx, fxLater) are registered in a group too, but are listed separately below
def explicitMethods = builder.localExplicitMethods

// Emit groups in the order of the builder's register*() methods; registrationGroups is unordered
def orderedGroups = [
    'SupportNodes', 'Binding', 'Stages', 'Layouts', 'Controls', 'Menus',
    'Shapes', 'Graphics', 'Charts', 'Effects', 'Transforms'
]
orderedGroups.addAll((groups.keySet() - orderedGroups.toSet()).sort())

orderedGroups.each { groupName ->
    def items = groups[groupName]?.findAll { !explicitMethods.containsKey(it) }
    if (!items) return

    out << "[[groovy-fx-group-${groupName.toLowerCase()}]]\n"
    out << "== ${categoryLabel(groupName)}\n\n"
    out << '[cols="2,3,1", options="header"]\n'
    out << "|===\n"
    out << "| Node Name | JavaFX Class | Leaf\n\n"

    items.sort().each { nodeName ->
        def factory = builder.factories[nodeName]
        def clazz = resolveClass(nodeName, factory)
        out << "| `${nodeName}`\n"
        out << "| ${clazz ? classLink(clazz) : '-'}\n"
        out << "| ${factory?.isLeaf() ?: false}\n\n"
    }
    out << "|===\n\n"
}

// Explicit methods section
if (explicitMethods) {
    def descriptions = [
        'fx'     : 'Runs a closure on the JavaFX application thread and waits for it, starting the toolkit if necessary.',
        'fxLater': 'Schedules a closure on the JavaFX application thread and returns immediately.',
    ]
    out << "[[groovy-fx-group-methods]]\n"
    out << "== Utility Methods\n\n"
    out << "These are explicit methods (not node factories) available on `SceneGraphBuilder`:\n\n"
    out << '[cols="2,4", options="header"]\n'
    out << "|===\n"
    out << "| Method | Description\n\n"
    explicitMethods.keySet().sort().each { name ->
        out << "| `${name}`\n"
        out << "| ${descriptions[name] ?: '-'}\n\n"
    }
    out << "|===\n\n"
}

outFile.text = out.toString()

println "Generated SceneGraphBuilder node documentation:"
println "  Output: ${outFile.absolutePath}"
println "  Categories: ${groups.size()}"
println "  Total nodes: ${builder.factories.size()}"
