package org.apache.groovy.ginq.provider.sql.runtime;

import groovy.sql.GroovyRowResult;
import groovy.sql.Sql;
import org.apache.groovy.ginq.provider.collection.runtime.Queryable;
import org.apache.groovy.lang.annotation.Incubating;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.ResultSetMetaData;
import java.sql.SQLException;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * Executes the SQL generated by the native SQL provider. The generated code
 * calls {@link #execute(Object, String, List)} with the compile-time constant
 * SQL text and the runtime parameter values.
 *
 * @since 6.0.0
 */
@Incubating
public final class SqlGinqRuntime {
    /**
     * Column added to each alias row when mixed mode re-zips a pushed join.
     * The value is the output-row index, so an in-memory equijoin on this
     * column reproduces the database join without re-evaluating it.
     */
    public static final String MIXED_KEY = "__ginq_mixed_key";

    /**
     * Runs the supplied SQL with the supplied bound parameters against the
     * supplied data source and returns the rows as a {@code Queryable}.
     * <p>
     * The data source may be a {@link Sql} instance or {@link Connection}
     * (used as-is; the caller owns their lifecycle), or a {@link DataSource}
     * (a connection is borrowed and released per query).
     *
     * @param dataSource the data source to query
     * @param sqlText the SQL text with {@code ?} placeholders
     * @param params the parameter values in placeholder order
     * @return the resulting rows
     * @throws SQLException if the query fails
     */
    public static Queryable<GroovyRowResult> execute(Object dataSource, String sqlText, List<Object> params) throws SQLException {
        if (dataSource instanceof Sql) {
            return Queryable.from(((Sql) dataSource).rows(sqlText, params));
        }
        if (dataSource instanceof DataSource) {
            Sql sql = new Sql((DataSource) dataSource);
            try {
                return Queryable.from(sql.rows(sqlText, params));
            } finally {
                sql.close();
            }
        }
        if (dataSource instanceof Connection) {
            return Queryable.from(new Sql((Connection) dataSource).rows(sqlText, params));
        }
        throw unsupported(dataSource);
    }

    /**
     * Returns the number of columns the supplied query produces. Used to split
     * a mixed-mode {@code alias.*} select list back into one row per alias.
     * The SQL text is a compile-time constant; values are bound as parameters.
     *
     * @param dataSource the data source to query
     * @param sqlText the SQL text with {@code ?} placeholders
     * @param params the parameter values in placeholder order
     * @return the column count
     * @throws SQLException if the query fails
     */
    public static int columnCount(Object dataSource, String sqlText, List<Object> params) throws SQLException {
        return withConnection(dataSource, connection -> {
            try (PreparedStatement statement = connection.prepareStatement(sqlText)) {
                bind(statement, params);
                try (ResultSet rs = statement.executeQuery()) {
                    return rs.getMetaData().getColumnCount();
                }
            }
        });
    }

    /**
     * Runs a mixed-mode prefix that projects {@code alias.*} for each alias,
     * in alias order, and splits every output row into one {@link GroovyRowResult}
     * per alias. Rows of each alias stay aligned by {@link #MIXED_KEY}.
     *
     * @param dataSource the data source to query
     * @param sqlText the SQL text with {@code ?} placeholders
     * @param params the parameter values in placeholder order
     * @param columnCounts the column count of each {@code alias.*}, in select-list order
     * @return one list of rows per alias
     * @throws SQLException if the query fails or the column layout does not match
     */
    public static List<List<GroovyRowResult>> zipAliases(Object dataSource, String sqlText, List<Object> params,
                                                         List<Integer> columnCounts) throws SQLException {
        int expected = 0;
        for (int count : columnCounts) {
            expected += count;
        }
        int aliasCount = columnCounts.size();
        List<List<GroovyRowResult>> byAlias = new ArrayList<>(aliasCount);
        for (int i = 0; i < aliasCount; i++) {
            byAlias.add(new ArrayList<>());
        }
        int columnTotal = expected;
        withConnection(dataSource, connection -> {
            try (PreparedStatement statement = connection.prepareStatement(sqlText)) {
                bind(statement, params);
                try (ResultSet rs = statement.executeQuery()) {
                    ResultSetMetaData metaData = rs.getMetaData();
                    if (metaData.getColumnCount() != columnTotal) {
                        throw new SQLException("mixed-mode result has " + metaData.getColumnCount()
                                + " columns but the alias layout expected " + columnTotal);
                    }
                    int rowIndex = 0;
                    while (rs.next()) {
                        int column = 1;
                        for (int alias = 0; alias < aliasCount; alias++) {
                            Map<String, Object> values = new LinkedHashMap<>();
                            int count = columnCounts.get(alias);
                            for (int c = 0; c < count; c++) {
                                String label = metaData.getColumnLabel(column);
                                if (label == null || label.isEmpty()) {
                                    label = metaData.getColumnName(column);
                                }
                                values.put(label, rs.getObject(column));
                                column++;
                            }
                            values.put(MIXED_KEY, rowIndex);
                            byAlias.get(alias).add(new GroovyRowResult(values));
                        }
                        rowIndex++;
                    }
                }
            }
            return null;
        });
        return byAlias;
    }

    private static void bind(PreparedStatement statement, List<Object> params) throws SQLException {
        if (params == null) {
            return;
        }
        for (int i = 0; i < params.size(); i++) {
            statement.setObject(i + 1, params.get(i));
        }
    }

    private static <T> T withConnection(Object dataSource, SqlWork<T> work) throws SQLException {
        if (dataSource instanceof Sql) {
            Sql sql = (Sql) dataSource;
            Connection connection = sql.getConnection();
            if (connection != null) {
                return work.run(connection);
            }
            DataSource nested = sql.getDataSource();
            if (nested == null) {
                throw unsupported(dataSource);
            }
            try (Connection borrowed = nested.getConnection()) {
                return work.run(borrowed);
            }
        }
        if (dataSource instanceof DataSource) {
            try (Connection borrowed = ((DataSource) dataSource).getConnection()) {
                return work.run(borrowed);
            }
        }
        if (dataSource instanceof Connection) {
            return work.run((Connection) dataSource);
        }
        throw unsupported(dataSource);
    }

    private static IllegalArgumentException unsupported(Object dataSource) {
        return new IllegalArgumentException("Unsupported dataSource: expected a groovy.sql.Sql, javax.sql.DataSource or java.sql.Connection but got: "
                + (dataSource == null ? "null" : dataSource.getClass().getName()));
    }

    @FunctionalInterface
    private interface SqlWork<T> {
        T run(Connection connection) throws SQLException;
    }

    /**
     * Builds a {@code LIKE} pattern from a runtime value, escaping the
     * wildcard characters {@code %} and {@code _} (and the escape character
     * itself) with {@code !}, matching the {@code ESCAPE '!'} clause the
     * renderer emits. Used for {@code contains}/{@code startsWith}/{@code endsWith}.
     *
     * @param value the value to match literally; {@code null} stays {@code null}
     *              so the predicate is unknown instead of matching the text {@code "null"}
     * @param matchBefore whether anything may precede the value
     * @param matchAfter whether anything may follow the value
     * @return the escaped pattern, or {@code null} when {@code value} is {@code null}
     */
    public static String likePattern(Object value, boolean matchBefore, boolean matchAfter) {
        if (value == null) {
            return null;
        }
        String escaped = String.valueOf(value)
                .replace("!", "!!")
                .replace("%", "!%")
                .replace("_", "!_");
        return (matchBefore ? "%" : "") + escaped + (matchAfter ? "%" : "");
    }

    private SqlGinqRuntime() {
    }
}
